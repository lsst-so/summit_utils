def getSlewsFromEventList(
    events: list[TMAEvent],
) -> list[TMAEvent]:
    """Get the slew events from a list of TMAEvents.

    Parameters
    ----------
    events : `list` of `lsst.summit.utils.tmaUtils.TMAEvent`
        The list of events to filter.

    Returns
    -------
    events : `list` of `lsst.summit.utils.tmaUtils.TMAEvent`
        The filtered list of events.
    """
    return [e for e in events if e.type == TMAState.SLEWING]


def getTracksFromEventList(
    events: list[TMAEvent],
) -> list[TMAEvent]:
    """Get the tracking events from a list of TMAEvents.

    Parameters
    ----------
    events : `list` of `lsst.summit.utils.tmaUtils.TMAEvent`
        The list of events to filter.

    Returns
    -------
    events : `list` of `lsst.summit.utils.tmaUtils.TMAEvent`
        The filtered list of events.
    """
    return [e for e in events if e.type == TMAState.TRACKING]


def getTorqueMaxima(table: pd.DataFrame) -> None:
    """Print the maximum positive and negative azimuth and elevation torques.

    Designed to be used with the table as downloaded from RubinTV.

    Parameters
    ----------
    table : `pd.DataFrame`
        The table of data to use, as generated by Rapid Analysis.
    """
    for axis in ["elevation", "azimuth"]:
        col = f"Largest {axis} torque"
        maxPos = np.argmax(table[col])
        maxVal = table[col].iloc[maxPos]
        print(f"Max positive {axis:9} torque during seqNum {maxPos:>4}: {maxVal / 1000:>7.1f}kNm")
        minPos = np.argmin(table[col])
        minVal = table[col].iloc[minPos]
        print(f"Max negative {axis:9} torque during seqNum {minPos:>4}: {minVal / 1000:>7.1f}kNm")
    return None


def getAzimuthElevationDataForEvent(
    client: EfdClient,
    event: TMAEvent,
    prePadding: float = 0,
    postPadding: float = 0,
    maxDeltaT: float = 1.0e-3,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Get the data for the az/el telemetry topics for a given TMAEvent.

    The error between the actual and demanded positions is calculated and added
    to the dataframes in the az/elError columns. For TRACKING type events, this
    error should be extremely close to zero, whereas for SLEWING type events,
    this error represents the how far the TMA is from the demanded position,
    and is therefore arbitrarily large, and tends to zero as the TMA get closer
    to tracking the sky.

    Parameters
    ----------
    client : `lsst_efd_client.efd_helper.EfdClient`
        The EFD client to use.
    event : `lsst.summit.utils.tmaUtils.TMAEvent`
        The event to get the data for.
    prePadding : `float`, optional
        The amount of time to pad the event with before the start time, in
        seconds.
    postPadding : `float`, optional
        The amount of time to pad the event with after the end time, in
        seconds.
    maxDeltaT : `float`, optional
        The maximum allowed time adjustment to bring the median error to
        zero, in seconds.

    Returns
    -------
    azimuthData : `pd.DataFrame`
        The azimuth data for the specified event.
    elevationData : `pd.DataFrame`
        The elevation data for the specified event.
    """

    def calcDeltaT(params, args):
        # This calculates the deltaT needed
        # to make the median(error) = 0
        [values, valTimes, demand, demTimes] = args
        [deltaT] = params
        demandInterp = np.interp(valTimes, demTimes + deltaT, demand)
        error = (values - demandInterp) * 3600
        value = abs(np.median(error))
        return value

    azimuthData = getEfdData(
        client,
        "lsst.sal.MTMount.azimuth",
        event=event,
        prePadding=prePadding,
        postPadding=postPadding,
        raiseIfTopicNotInSchema=False,
    )
    elevationData = getEfdData(
        client,
        "lsst.sal.MTMount.elevation",
        event=event,
        prePadding=prePadding,
        postPadding=postPadding,
        raiseIfTopicNotInSchema=False,
    )

    azValues = np.asarray(azimuthData["actualPosition"])
    azValTimes = np.asarray(azimuthData["actualPositionTimestamp"])
    azDemand = np.asarray(azimuthData["demandPosition"])
    azDemTimes = np.asarray(azimuthData["demandPositionTimestamp"])
    elValues = np.asarray(elevationData["actualPosition"])
    elValTimes = np.asarray(elevationData["actualPositionTimestamp"])
    elDemand = np.asarray(elevationData["demandPosition"])
    elDemTimes = np.asarray(elevationData["demandPositionTimestamp"])

    # Calculate the deltaT needed to drive the median(error) to zero
    args = [azValues, azValTimes, azDemand, azDemTimes]
    x0 = [0.0]
    result = minimize(calcDeltaT, x0, args=args, method="Powell", bounds=[(-maxDeltaT, maxDeltaT)])
    deltaTAz = result.x[0]

    args = [elValues, elValTimes, elDemand, elDemTimes]
    x0 = [0.0]
    result = minimize(calcDeltaT, x0, args=args, method="Powell", bounds=[(-maxDeltaT, maxDeltaT)])
    deltaTEl = result.x[0]

    azDemandInterp = np.interp(azValTimes, azDemTimes + deltaTAz, azDemand)
    elDemandInterp = np.interp(elValTimes, elDemTimes + deltaTEl, elDemand)

    azError = (azValues - azDemandInterp) * 3600
    elError = (elValues - elDemandInterp) * 3600

    azimuthData["azError"] = azError
    elevationData["elError"] = elError

    return azimuthData, elevationData


def getM1M3HardpointDataForEvent(
    client: EfdClient,
    event: TMAEvent,
    prePadding: float = 0,
    postPadding: float = 0,
) -> pd.DataFrame:
    """Get the data for the M1M3 hardpoint telemetry for a given TMAEvent.
    During slews, the M1M3 mirror moves in response to the accelerations. The
    hardpoint forces need to stay within accepted limits to prevent long term
    cracking on the mirror.

    Parameters
    ----------
    client : `lsst_efd_client.efd_helper.EfdClient`
        The EFD client to use.
    event : `lsst.summit.utils.tmaUtils.TMAEvent`
        The event to get the data for.
    prePadding : `float`, optional
        The amount of time to pad the event with before the start time, in
        seconds.
    postPadding : `float`, optional
        The amount of time to pad the event with after the end time, in
        seconds.

    Returns
    -------
    hardpointData : `pd.DataFrame`
        The hardpoint forces for the specified event.
    """
    hardpointData = getEfdData(
        client,
        "lsst.sal.MTM1M3.hardpointActuatorData",
        event=event,
        prePadding=prePadding,
        postPadding=postPadding,
        raiseIfTopicNotInSchema=False,
    )

    # Add a column with the absolute max force
    maxForce = [
        np.nanmax([abs(hardpointData.iloc[i][f"measuredForce{j}"]) for j in range(6)])
        for i in range(len(hardpointData))
    ]

    hardpointData["maxForce"] = maxForce

    return hardpointData


def filterBadValues(values: list | np.ndarray, maxDelta: float = 0.1, maxConsecutiveValues: int = 3) -> int:
    """Filter out bad values from a dataset, replacing them in-place.

    This function replaces non-physical points in the dataset with an
    extrapolation of the preceding two values. No more than 3 successive data
    points are allowed to be replaced. Minimum length of the input is 3 points.

    Parameters
    ----------
    values : `list` or `np.ndarray`
        The dataset containing the values to be filtered.
    maxDelta : `float`, optional
        The maximum allowed difference between consecutive values. Values with
        a difference greater than `maxDelta` will be considered as bad values
        and replaced with an extrapolation.
    maxConsecutiveValues : `int`, optional
        The maximum number of consecutive values to replace. Defaults to 3.

    Returns
    -------
    nBadPoints : `int`
        The number of bad values that were replaced out.
    """
    # Find non-physical points and replace with extrapolation. No more than
    # maxConsecutiveValues successive data points can be replaced.
    badCounter = 0
    consecutiveCounter = 0

    log = logging.getLogger(__name__)

    median = np.nanmedian(values)
    # if either of the the first two points are more than maxDelta away from
    # the median, replace them with the median
    for i in range(2):
        if abs(values[i] - median) > maxDelta:
            log.warning(f"Replacing bad value of {values[i]} at index {i} with {median=}")
            values[i] = median
            badCounter += 1

    # from the second element of the array, walk through and calculate the
    # difference between each element and the previous one. If the difference
    # is greater than maxDelta, replace the element with the average of the
    # previous two known good values, i.e. ones which have not been replaced.
    # if the first two points differ from the median by more than maxDelta,
    # replace them with the median
    lastGoodValue1 = values[1]  # the most recent good value
    lastGoodValue2 = values[0]  # the second most recent good value
    replacementValue = (lastGoodValue1 + lastGoodValue2) / 2.0  # in case we have to replace the first value
    for i in range(2, len(values)):
        if abs(values[i] - lastGoodValue1) >= maxDelta:
            if consecutiveCounter < maxConsecutiveValues:
                consecutiveCounter += 1
                badCounter += 1
                log.warning(f"Replacing value at index {i} with {replacementValue}")
                values[i] = replacementValue
            else:
                log.warning(
                    f"More than 3 consecutive replacements at index {i}. Stopping replacements"
                    " until the next good value."
                )
        else:
            lastGoodValue2 = lastGoodValue1
            lastGoodValue1 = values[i]
            replacementValue = (lastGoodValue1 + lastGoodValue2) / 2.0
            consecutiveCounter = 0
    return badCounter


def plotEvent(
    client: EfdClient,
    event: TMAEvent,
    fig: matplotlib.figure.Figure | None = None,
    prePadding: float = 0,
    postPadding: float = 0,
    commands: dict[pd.Timestamp | datetime.datetime, str] = {},
    azimuthData: pd.DataFrame | None = None,
    elevationData: pd.DataFrame | None = None,
    hardpointData: pd.DataFrame | None = None,
    doFilterResiduals: bool = False,
    maxDelta: float = 0.1,
    metadataWriter: Callable | None = None,
) -> matplotlib.figure.Figure:
    """Plot the TMA axis positions over the course of a given TMAEvent.

    Plots the axis motion profiles for the given event, with optional padding
    at the start and end of the event. If the data is provided via the
    azimuthData and elevationData parameters, it will be used, otherwise it
    will be queried from the EFD.  For slews, the M1M3 hardpoint forces are
    also plotted.  Similarly, it will query the EFD if the hardpoint forces are
    not provided.

    Optionally plots any commands issued during or around the event, if these
    are supplied. Commands are supplied as a dictionary of tje times at which
    the commands were issued, with values as command strings.

    Due to a problem with the way the data is uploaded to the EFD, there are
    occasional points in the tracking error plots that are very much larger
    than the typical mount jitter. These points are unphysical, since it is not
    possible for the mount to move that fast. We don't want these points, which
    are not true mount problems, to distract from any real mount problems, and
    these can be filtered out via the ``doFilterResiduals`` kwarg, which
    replaces these non-physical points with an extrapolation of the average of
    the preceding two known-good points. If the first two points are bad these
    are replaced with the median of the dataset. The maximum difference between
    the model and the actual data, in arcseconds, to allow before filtering a
    data point can be set with the ``maxDelta`` kwarg.

    Parameters
    ----------
    client : `lsst_efd_client.efd_helper.EfdClient`
        The EFD client to use.
    event : `lsst.summit.utils.tmaUtils.TMAEvent`
        The event to plot.
    fig : `matplotlib.figure.Figure`, optional
        The figure to plot on. If not specified, a new figure will be created.
    prePadding : `float`, optional
        The amount of time to pad the event with before the start time, in
        seconds.
    postPadding : `float`, optional
        The amount of time to pad the event with after the end time, in
        seconds.
    commands : `dict` [`pd.Timestamp`, `str`], or
               `dict` [`datetime.datetime`, `str`], or optional
        A dictionary of commands to plot on the figure. The keys are the times
        at which a command was issued, and the value is the command string, as
        returned by efdUtils.getCommands().
    azimuthData : `pd.DataFrame`, optional
        The azimuth data to plot. If not specified, it will be queried from the
        EFD.
    elevationData : `pd.DataFrame`, optional
        The elevation data to plot. If not specified, it will be queried from
        the EFD.
    hardpointData : `pd.DataFrame`, optional
        The hardpoint forces to plot. If not specified, it will be queried from
        the EFD.
    doFilterResiduals : 'bool', optional
        Enables filtering of unphysical data points in the tracking residuals.
    maxDelta : `float`, optional
        The maximum difference between the model and the actual data, in
        arcseconds, to allow before filtering the data point. Ignored if
        ``doFilterResiduals`` is `False`.
    metadataWriter : `callable`, optional
        Should be a callable
        ``lsst.rubintv.production.utils.writeMetadataShard`` function that has
        had the path filled in with ``functools.patrial`` so that it will just
        write out the data when called with the event's dayObs and a dictionary
        containing the row data that should be written.

    Returns
    -------
    fig : `matplotlib.figure.Figure`
        The figure on which the plot was made.
    """

    def tickFormatter(value: float, tick_number: float) -> str:
        # Convert the value to a string without subtracting large numbers
        # tick_number is unused.
        return f"{value:.2f}"

    def getPlotTime(time: pd.Timestamp | Time | datetime.datetime) -> datetime.datetime:
        """Get the right time to plot a point from the various time formats."""
        match time:
            case pd.Timestamp():
                return time.to_pydatetime()
            case astropy.time.Time():
                return time.utc.datetime
            case datetime.datetime():
                return time
            case _:
                raise ValueError(f"Unknown type for commandTime: {type(time)}")

    # plot any commands we might have
    if not isinstance(commands, dict):
        raise TypeError("commands must be a dict of command names with values as" " astropy.time.Time values")

    if fig is None:
        fig = make_figure(figsize=(10, 8))
        log = logging.getLogger(__name__)
        log.warning(
            "Making new matplotlib figure - if this is in a loop you're going to have a bad time."
            " Pass in a figure with fig = plt.figure(figsize=(10, 8)) to avoid this warning."
        )

    fig.clear()
    ax1, ax1p5, ax2 = fig.subplots(
        3, sharex=True, gridspec_kw={"wspace": 0, "hspace": 0, "height_ratios": [2.5, 1, 1]}
    )  # type: ignore

    if azimuthData is None or elevationData is None:
        azimuthData, elevationData = getAzimuthElevationDataForEvent(
            client, event, prePadding=prePadding, postPadding=postPadding
        )

    assert azimuthData is not None
    assert elevationData is not None

    # Use the native color cycle for the lines. Because they're on different
    # axes they don't cycle by themselves
    lineColors = [p["color"] for p in plt.rcParams["axes.prop_cycle"]]
    nColors = len(lineColors)
    colorCounter = 0

    ax1.plot(azimuthData["actualPosition"], label="Azimuth position", c=lineColors[colorCounter % nColors])
    colorCounter += 1
    ax1.yaxis.set_major_formatter(FuncFormatter(tickFormatter))
    ax1.set_ylabel("Azimuth (degrees)")

    ax1_twin = ax1.twinx()
    ax1_twin.plot(
        elevationData["actualPosition"], label="Elevation position", c=lineColors[colorCounter % nColors]
    )
    colorCounter += 1
    ax1_twin.yaxis.set_major_formatter(FuncFormatter(tickFormatter))
    ax1_twin.set_ylabel("Elevation (degrees)")
    ax1.set_xticks([])  # remove x tick labels on the hidden upper x-axis

    ax2_twin = ax2.twinx()
    ax2.plot(azimuthData["actualTorque"], label="Azimuth torque", c=lineColors[colorCounter % nColors])
    colorCounter += 1
    ax2_twin.plot(
        elevationData["actualTorque"], label="Elevation torque", c=lineColors[colorCounter % nColors]
    )
    colorCounter += 1
    ax2.set_ylabel("Azimuth torque (Nm)")
    ax2_twin.set_ylabel("Elevation torque (Nm)")
    ax2.set_xlabel("Time (UTC)")  # yes, it really is UTC, matplotlib converts this automatically!

    if event.type == TMAState.TRACKING:
        # returns a copy
        clippedAzimuthData = clipDataToEvent(azimuthData, event, postPadding=TRACKING_RESIDUAL_TAIL_CLIP)
        clippedElevationData = clipDataToEvent(elevationData, event, postPadding=TRACKING_RESIDUAL_TAIL_CLIP)

        azError = clippedAzimuthData["azError"].to_numpy()
        elError = clippedElevationData["elError"].to_numpy()
        elVals = clippedElevationData["actualPosition"].to_numpy()

        if doFilterResiduals:
            # Filtering out bad values
            nReplacedAz = filterBadValues(azError, maxDelta)
            nReplacedEl = filterBadValues(elError, maxDelta)
            clippedAzimuthData["azError"] = azError
            clippedElevationData["elError"] = elError
            replacementMsg = (
                f"{nReplacedAz} bad azimuth values and {nReplacedEl} bad elevation values were replaced"
            )
        else:
            # currently unused, but needed for mypy, and better than an
            # alternative in case someone redesigns that part later
            replacementMsg = "No values were replaced because doFilterResiduals is False"

        # Calculate RMS
        az_rms = np.sqrt(np.mean(azError * azError))
        el_rms = np.sqrt(np.mean(elError * elError))

        # Calculate Image impact RMS
        # We are less sensitive to Az errors near the zenith
        image_az_rms = az_rms * np.cos(elVals[0] * np.pi / 180.0)
        image_el_rms = el_rms
        image_impact_rms = np.sqrt(image_az_rms**2 + image_el_rms**2)

        ax1p5.plot(
            clippedAzimuthData["azError"],
            label="Azimuth tracking error",
            c=lineColors[colorCounter % nColors],
        )
        colorCounter += 1
        ax1p5.plot(
            clippedElevationData["elError"],
            label="Elevation tracking error",
            c=lineColors[colorCounter % nColors],
        )
        colorCounter += 1
        ax1p5.axhline(0.01, ls="-.", color="black")
        ax1p5.axhline(-0.01, ls="-.", color="black")
        ax1p5.yaxis.set_major_formatter(FuncFormatter(tickFormatter))
        ax1p5.set_ylabel("Tracking error (arcsec)")
        ax1p5.set_xticks([])  # remove x tick labels on the hidden upper x-axis
        ax1p5.set_ylim(-0.05, 0.05)
        ax1p5.set_yticks([-0.04, -0.02, 0.0, 0.02, 0.04])
        ax1p5.legend()
        ax1p5.text(0.1, 0.9, f"Image impact RMS = {image_impact_rms:.3f} arcsec", transform=ax1p5.transAxes)
        if doFilterResiduals:
            ax1p5.text(
                0.1,
                0.8,
                replacementMsg,
                transform=ax1p5.transAxes,
            )
        if metadataWriter is not None:
            md = {"Tracking image impact": f"{image_impact_rms:.3f}"}
            flagKey = "_Tracking image impact"
            if image_impact_rms > MOUNT_IMAGE_BAD_LEVEL:
                md.update({flagKey: "bad"})
            elif image_impact_rms > MOUNT_IMAGE_WARNING_LEVEL:
                md.update({flagKey: "warning"})

            rowData = {event.seqNum: md}
            metadataWriter(dayObs=event.dayObs, mdDict=rowData)

    elif event.type == TMAState.SLEWING:
        if hardpointData is None:
            hardpointData = getM1M3HardpointDataForEvent(
                client, event, prePadding=prePadding, postPadding=postPadding
            )

        if not hardpointData.empty:
            # Calculate Max hardpoint force
            maxForce = np.nanmax(hardpointData["maxForce"].to_numpy())

            for hp_index in range(6):
                ax1p5.plot(
                    hardpointData[f"measuredForce{hp_index}"],
                    label=f"HP_{hp_index}",
                    c=lineColors[colorCounter % nColors],
                )
                colorCounter += 1
            ax1p5.axhline(500.0, ls="-.", color="goldenrod")
            ax1p5.axhline(-500.0, ls="-.", color="goldenrod")
            ax1p5.axhline(1000.0, ls="-.", color="red")
            ax1p5.axhline(-1000.0, ls="-.", color="red")
            ax1p5.yaxis.set_major_formatter(FuncFormatter(tickFormatter))
            ax1p5.set_ylabel("HP force (N)")
            ax1p5.set_xticks([])  # remove x tick labels on the hidden upper x-axis
            if maxForce > 2000.0:
                ax1p5.set_ylim(-4000.0, 4000.0)
                ax1p5.set_yticks([-2000, 0.0, 2000])
            elif maxForce > 1000.0:
                ax1p5.set_ylim(-2000.0, 2000.0)
                ax1p5.set_yticks([-1000, 0.0, 1000])
            else:
                ax1p5.set_ylim(-1000.0, 1000.0)
                ax1p5.set_yticks([-500, 0.0, 500])
            ax1p5.legend()
            ax1p5.text(0.1, 0.9, f"Max HP force = {maxForce:.1f} N", transform=ax1p5.transAxes)

            if metadataWriter is not None:
                md = {"HP Max force": f"{maxForce:.2f}"}
                flagKey = "_HP Max force"
                if maxForce > HARDPOINT_FORCE_BAD_LEVEL:
                    md.update({flagKey: "bad"})
                elif maxForce > HARDPOINT_FORCE_WARNING_LEVEL:
                    md.update({flagKey: "warning"})

                rowData = {event.seqNum: md}
                metadataWriter(dayObs=event.dayObs, mdDict=rowData)

    if prePadding or postPadding:
        # note the conversion to utc because the x-axis from the dataframe
        # already got automagically converted when plotting before, so this is
        # necessary for things to line up
        ax1_twin.axvline(event.begin.utc.datetime, c="k", ls="--", alpha=0.5, label="Event begin/end")
        ax1_twin.axvline(event.end.utc.datetime, c="k", ls="--", alpha=0.5)
        # extend lines down across lower plot, but do not re-add label
        ax2_twin.axvline(event.begin.utc.datetime, c="k", ls="--", alpha=0.5)
        ax2_twin.axvline(event.end.utc.datetime, c="k", ls="--", alpha=0.5)
        ax1p5.axvline(event.begin.utc.datetime, c="k", ls="--", alpha=0.5)
        ax1p5.axvline(event.end.utc.datetime, c="k", ls="--", alpha=0.5)

    for commandTime, command in commands.items():
        plotTime = getPlotTime(commandTime)
        ax1_twin.axvline(
            plotTime, c=lineColors[colorCounter % nColors], ls="--", alpha=0.75, label=f"{command}"
        )
        # extend lines down across lower plot, but do not re-add label
        ax2_twin.axvline(plotTime, c=lineColors[colorCounter % nColors], ls="--", alpha=0.75)
        ax1p5.axvline(plotTime, c=lineColors[colorCounter % nColors], ls="--", alpha=0.75)
        colorCounter += 1

    # combine the legends and put inside the plot
    handles1a, labels1a = ax1.get_legend_handles_labels()
    handles1b, labels1b = ax1_twin.get_legend_handles_labels()
    handles2a, labels2a = ax2.get_legend_handles_labels()
    handles2b, labels2b = ax2_twin.get_legend_handles_labels()

    handles = handles1a + handles1b + handles2a + handles2b
    labels = labels1a + labels1b + labels2a + labels2b
    # ax2 is "in front" of ax1 because it has the vlines plotted on it, and
    # vlines are on ax2 so that they appear at the bottom of the legend, so
    # make sure to plot the legend on ax2, otherwise the vlines will go on top
    # of the otherwise-opaque legend.
    ax1_twin.legend(handles, labels, facecolor="white", framealpha=1)

    # Add title with the event name, type etc
    dayObsStr = dayObsIntToString(event.dayObs)
    title = (
        # top line is the event title, the details go on the line below
        f"{dayObsStr} - seqNum {event.seqNum} (version {event.version})"
        f"\nDuration = {event.duration:.2f}s"
        f" Event type: {event.type.name}"
        f" End reason: {event.endReason.name}"
    )
    ax1_twin.set_title(title)

    # Moving this block to the end recovers the time ticks and ticklabels.
    # put the ticks at an angle, and right align with the tick marks
    ax2.set_xticks(ax2.get_xticks())  # needed to supress a user warning
    xlabels = ax2.get_xticks()
    ax2.set_xticklabels(xlabels, rotation=40, ha="right")
    ax2.xaxis.set_major_locator(mdates.AutoDateLocator())
    ax2.xaxis.set_major_formatter(mdates.DateFormatter("%H:%M:%S"))

    return fig


def getCommandsDuringEvent(
    client: EfdClient,
    event: TMAEvent,
    commands: Iterable[str] = ("raDecTarget",),
    prePadding: float = 0,
    postPadding: float = 0,
    timeFormat: str = "python",
    log: logging.Logger | None = None,
    doLog: bool = True,
) -> dict[datetime.datetime, str]:
    """Get the commands issued during an event.

    Get the times at which the specified commands were issued during the event.

    Parameters
    ----------
    client : `lsst_efd_client.efd_helper.EfdClient`
        The EFD client to use.
    event : `lsst.summit.utils.tmaUtils.TMAEvent`
        The event to plot.
    commands : `list` of `str`, optional
        The commands or command aliases to look for. Defaults to
        ['raDecTarget'].
    prePadding : `float`, optional
        The amount of time to pad the event with before the start time, in
        seconds.
    postPadding : `float`, optional
        The amount of time to pad the event with after the end time, in
        seconds.
    timeFormat : `str`, optional
        One of 'pandas' or 'astropy' or 'python'. If 'pandas', the dictionary
        keys will be pandas timestamps, if 'astropy' they will be astropy times
        and if 'python' they will be python datetimes.
    log : `logging.Logger`, optional
        The logger to use. If not specified, a new logger will be created if
        needed.
    doLog : `bool`, optional
        Whether to log messages. Defaults to True.

    Returns
    -------
    commandTimes : `dict` [`time`, `str`]
        A dictionary of the times at which the commands where issued. The type
        that `time` takes is determined by the format key, and defaults to
        python datetime.
    """
    commands = list(ensure_iterable(commands))
    fullCommands = [c if c not in COMMAND_ALIASES else COMMAND_ALIASES[c] for c in commands]
    del commands  # make sure we always use their full names

    commandTimes = getCommands(
        client,
        fullCommands,
        begin=event.begin,
        end=event.end,
        prePadding=prePadding,
        postPadding=postPadding,
        timeFormat=timeFormat,
    )

    if not commandTimes and doLog:
        log = logging.getLogger(__name__)
        log.info(f"Found no commands in {fullCommands} issued during event {event.seqNum}")

    return commandTimes


